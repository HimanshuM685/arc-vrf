// Writes src/generated.ts from Foundry artifacts (contracts/out) and deployments (contracts/deployments).
// Run after `forge build` and after each deploy: pnpm --filter @arc-vrf/sdk gen
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('../../../contracts/', import.meta.url).pathname
const names = ['ArcVRFCoordinator', 'ArcVRFWrapper', 'BlockhashStore', 'BatchArcVRFCoordinator', 'HiLoGame', 'DiceDirect']

let out = '// Generated by packages/sdk/scripts/gen.ts. Do not edit.\n\n'
for (const n of names) {
  const art = JSON.parse(readFileSync(join(root, 'out', `${n}.sol`, `${n}.json`), 'utf8'))
  const abiName = n[0]!.toLowerCase() + n.slice(1) + 'Abi'
  out += `export const ${abiName} = ${JSON.stringify(art.abi, null, 2)} as const\n\n`
}

const depDir = join(root, 'deployments')
const deployments: Record<string, unknown> = {}
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir).filter((f) => f.endsWith('.json'))) {
    deployments[f.replace('.json', '')] = JSON.parse(readFileSync(join(depDir, f), 'utf8'))
  }
}
out += `export const deployments = ${JSON.stringify(deployments, null, 2)} as const\n`
writeFileSync(new URL('../src/generated.ts', import.meta.url), out)
console.log(`wrote ABIs for ${names.length} contracts, deployments for chains: ${Object.keys(deployments).join(', ') || 'none'}`)
